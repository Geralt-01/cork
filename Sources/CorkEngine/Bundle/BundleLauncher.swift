import Foundation

/// Builds the `Contents/MacOS/<name>` launcher for a generated `.app`.
///
/// ## Mechanism
///
/// The launcher is a small `bash` script. It does **not** embed or require a
/// Wine runtime at bundle time (so bundling is unit-testable on a machine with
/// no runtime installed). At *launch* time it resolves the `cork` CLI and
/// delegates to `cork run <bottle> <exe> [args…] "$@"`, which in turn resolves
/// the Wine runtime, prepares the bottle environment and runs the program.
///
/// `cork` is resolved in this order:
///  1. `$CORK_BIN` (if it points at an executable);
///  2. self-contained fallbacks next to the bundle
///     (`Contents/Resources/cork`, `Contents/MacOS/cork`) so an app can ship
///     alongside a Cork binary without relying on an absolute path;
///  3. common install locations (`/usr/local/bin`, Homebrew, `~/.local/bin`,
///     `~/bin`);
///  4. `cork` found on `PATH`.
///
/// The bottle, executable and default arguments are baked into the script with
/// shell quoting, so no JSON parser is needed at runtime. The same values are
/// also written to `Contents/Resources/launch.json` for tooling.
enum BundleLauncher {
    /// The complete launcher script for the given program.
    static func script(
        appName: String,
        bottle: String,
        executable: String,
        arguments: [String]
    ) -> String {
        let command = (["run", bottle, executable] + arguments)
            .map(shellQuote)
            .joined(separator: " ")

        return """
        #!/bin/bash
        # Generated by Cork. Launches \(appName) in the '\(bottle)' bottle.
        #
        # The Wine runtime is resolved at launch time by the 'cork' CLI; this
        # script only needs to find the 'cork' executable.
        set -euo pipefail

        APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

        find_cork() {
          if [[ -n "${CORK_BIN:-}" && -x "${CORK_BIN}" ]]; then
            printf '%s\\n' "${CORK_BIN}"
            return 0
          fi
          local candidates=(
            "${APP_DIR}/Contents/Resources/cork"
            "${APP_DIR}/Contents/MacOS/cork"
            "/usr/local/bin/cork"
            "/opt/homebrew/bin/cork"
            "${HOME}/.local/bin/cork"
            "${HOME}/bin/cork"
          )
          local candidate
          for candidate in "${candidates[@]}"; do
            if [[ -x "${candidate}" ]]; then
              printf '%s\\n' "${candidate}"
              return 0
            fi
          done
          if command -v cork >/dev/null 2>&1; then
            command -v cork
            return 0
          fi
          return 1
        }

        CORK="$(find_cork || true)"
        if [[ -z "${CORK}" ]]; then
          echo "Cork: could not find the 'cork' executable. Set CORK_BIN to its path." >&2
          exit 127
        fi

        exec "${CORK}" \(command) "$@"
        """
    }

    /// Quotes a string for safe use as a single `bash` word.
    ///
    /// Wraps the value in single quotes and escapes embedded single quotes,
    /// which also makes newlines and other shell metacharacters literal.
    static func shellQuote(_ value: String) -> String {
        "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }
}
